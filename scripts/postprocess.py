#!/usr/bin/env python3

import argparse
import math
import collections
import concurrent.futures
from relion30_to_31 import relion30_to_31
from remove_repeat_particles_from_one_micrograph import remove_repeat_particles_from_one_micrograph

def remove_repeat(*args):
    return remove_repeat_particles_from_one_micrograph(*args)

def postprocess_lst(inlst, center, euler_thres, scale, apix, output, score_threshold, cpu):
    output = inlst.split('.lst')[0] + f'_{score_threshold}' + output
    with open(inlst, "r") as g:
        inlst_lines = g.readlines()
    mg2ptcL = collections.defaultdict(list)
    for l in inlst_lines: mg2ptcL[ l.split('\t')[1] ].append(l)
    pool = concurrent.futures.ProcessPoolExecutor(cpu)
    fuL = [pool.submit(remove_repeat, ps, center, euler_thres, score_threshold) for ps in mg2ptcL.values()]
    inlst_lines = [l for fu in fuL for l in fu.result()]

    # 将lst文件转换为star文件

    data = []
    for i in inlst_lines:
        file_path = i.split('\t')[1] # 照片文件路径
        if scale!=1: file_path = file_path.replace(f'/bin{scale}', '')
        micrograph_name = file_path
        df = float(i.split('\t')[2].split('=')[1])*10000 # 欠焦值 (angstrom)
        dfdiff = float(i.split('\t')[3].split('=')[1])*10000 # 像散 (angstrom)
        dfu = df - dfdiff
        dfv = df + dfdiff
        dfang = float(i.split('\t')[4].split('=')[1])
        #ox = float(inlst_line2[m+3].split('\t')[5].split('=')[1].split(',')[0])
        #oy = float(inlst_line2[m+3].split('\t')[5].split('=')[1].split(',')[1])
        euler1 = float(i.split('\t')[5].split('=')[1].split(',')[0])
        euler2 = float(i.split('\t')[5].split('=')[1].split(',')[1])
        euler3 = float(i.split('\t')[5].split('=')[1].split(',')[2])
        score = float(i.split('\t')[7].split('=')[1])
        #   m[i-3] = int(inlst_lines[i].split('\t')[0])
        #s5 = "euler="
        #s6 = "center="
        cx = (float(i.split('\t')[6].split('=')[1].split(',')[0]))*scale
        cy = (float(i.split('\t')[6].split('=')[1].split(',')[1]))*scale
        dfu = round(dfu, 10) # 浮点数误差
        dfv = round(dfv, 10)
        # 将EMAN2的Euler角方式转换为RELION的Euler角方式
        euler1 = round(euler1, 4)
        euler2 = math.fmod(euler2-90, 360)
        euler2 = round(euler2, 4)
        euler3 = math.fmod(euler3+90, 360)
        euler3 = round(euler3, 4)
        data.append(str(micrograph_name)+"\t"+str(cx)+"\t"+str(cy)+"\t"+str(dfu)+"\t"+str(dfv)+"\t"+str(dfang)+"\t300.000000\t2.700000\t0.070000\t"+str(apix)+"\t"+str(euler2)+"\t"+str(euler1)+"\t"+str(euler3)+"\t"+str(score)+"\n")
    with open(output, "w") as oo:
        oo.write("# RELION; version 3.0-beta-2\n\ndata_\n\nloop_\n_rlnMicrographName #1 \n_rlnCoordinateX #2 \n_rlnCoordinateY #3 \n_rlnDefocusU #4 \n_rlnDefocusV #5 \n_rlnDefocusAngle #6 \n_rlnVoltage #7 \n_rlnSphericalAberration #8 \n_rlnAmplitudeContrast #9 \n_rlnDetectorPixelSize #10 \n_rlnAngleRot #11 \n_rlnAngleTilt #12 \n_rlnAnglePsi #13 \n_rlnAutopickFigureOfMerit #14 \n")
        for j in data:
            oo.write(j)
    return output


def parse_command_line():
    #提取输入的各个参数
    #usage = "%prog <Detection file> <Number of windows> <Center threshold> <Euler threshold> <Output>"
    parser = argparse.ArgumentParser(description='Remove duplicated particles')
    parser.add_argument('input', metavar='Input_file', help='The .lst file generated by isSPA from target detection')
    parser.add_argument('center', metavar='dist_threshold', type=float, help='The largest distance (pixel) between duplicated points')
    parser.add_argument('euler', metavar='Angle_threshold', type=float, help='The largest angle between two Euler angles')
    parser.add_argument('--bin', metavar = 'N', type=int, default = 1, help='The bining factor used during preprocess.py and target detection')
    parser.add_argument('pixel', metavar='Pixel_size', type=float, help='The original pixel size (angstrom) of the original micrograph')
    parser.add_argument('--score', metavar='R', type=float, default = 6.0, help='The score threshold used to filter particles')
    parser.add_argument('-o', metavar='--output', dest='output', default='_merge.star', help='The output file. Default name: {input}_merge.star')
    parser.add_argument('--cpu', metavar='N', type=int, help='The number of CPU used')

    args = parser.parse_args()

    inlst = args.input
    center = args.center
    euler_thres = args.euler
    scale = args.bin
    apix = args.pixel
    output = args.output

    return inlst, center, euler_thres, scale, apix, output, args.score, args.cpu

def main():
    relion30 = postprocess_lst(*parse_command_line())
    relion30_to_31(relion30, '_31.star')

if __name__== "__main__":
    main()