#!/usr/bin/env python3

import argparse
import os
import subprocess

import starfile

from read_line_format import read_line_format
from write_lst import write_lst

"""
缩小所有照片的尺寸并放到一个文件夹中，将micrograph_ctf.star转换为micrograph_ctf.lst
"""

parser = argparse.ArgumentParser(description='This program will bin all the micrographs and put them in a directory. Then it will convert .star file to .lst file')
parser.add_argument('--bin', metavar='Bin_factor', type=int, default = 1, help='The bin factor you would like to use, default is %(default)s')
parser.add_argument('star', metavar='STAR_file', help='The .star file generated by RELION after CTF estimation')
parser.add_argument('-o', '--output', metavar='PATH', default='micrograph_ctf.lst', help='The output file. Default: %(default)s')

args = parser.parse_args()
bin_factor = args.bin
instar = args.star
lst = args.output

if bin_factor > 1:
    star = starfile.read(args.star)
    pixel = star['optics']['rlnMicrographPixelSize'][0]
    pixel_b = pixel * bin_factor
    file_list = star['micrographs']['rlnMicrographName'].tolist()
    
if bin_factor > 1:
    # 创建文件夹
    for j,f in enumerate(file_list):
        new_dir = os.path.dirname(f)+f'/bin{bin_factor}'
        os.makedirs(new_dir, exist_ok=True)
        p = subprocess.Popen(f'relion_image_handler --i {f} --o {new_dir}/{os.path.basename(f)} --angpix {pixel} --rescale_angpix {pixel_b} >> preprocess.log', shell=True)
        if j != 0:
            if j % 12 == 0:
                p.wait()
                print(f' {j} micrographs are binned!\n')
        if j == len(file_list)-1:
            p.wait()
                #time.sleep(5)

fnum = 0 # image number in new file

star_format = read_line_format(instar)
if star_format[-1] == 0:
    spliter = " "
elif star_format[-1] == 1:
    spliter = "\t"
with open(instar, 'r') as f:
    lines = f.readlines()

if len(star_format) == 3:
    write_lst(lines, star_format, lst, 0, spliter, fnum, bin_factor)
else:
    write_lst(lines, star_format, lst, 1, spliter, fnum, bin_factor)

print(" All tasks are finished!\n")