#!/usr/bin/env python3
# coding: utf-8


import argparse
import numpy as np
import starfile

def main():
    ap = argparse.ArgumentParser(description="Rescore particles by weighted amplitude-phase Fourier CC")
    ap.add_argument("-i", "--input", required=True, help="particles STAR file")
    ap.add_argument("-s", "--score", help = ".npy file generated by score_particles.py")
    ap.add_argument("-o", "--out", required=False, help="Output STAR file of particles subset")
    ap.add_argument("--thres", type=float, help = "select particles with scores greater than this threshold")
    ap.add_argument("--quantile", type=float, help = "select particles with scores above the specified quantile")

    args = ap.parse_args()
    if args.score is None: args.score = args.input.replace('.star', '.npy')
    if args.out is None:   args.out = args.input.replace('.star', '_sub.star')
    assert args.thres or args.quantile, "must specify --thres or --quantile"
    score = np.load(args.score)
    if args.thres is None: args.thres = score.min()
    if args.quantile: args.thres = max( np.quantile(score, args.quantile), args.thres )

    star = starfile.read(args.input) 
    star['particles'] = star['particles'][score>=args.thres]
    starfile.write(star, args.out)

if __name__ == "__main__":
    main()
